async def one(k,t):
    c=edge_tts.Communicate(t,'ar-SA-ZariyahNeural',rate='-10%',boundary='WordBoundary');w=[]
    with open(f'vox/{k}.mp3','wb') as f:
        async for ch in c.stream():
            if ch['type']=='audio':f.write(ch['data'])
            elif ch['type']=='WordBoundary':w.append([ch['offset']/1e7,ch['duration']/1e7,ch['text']])
    json.dump(w,open(f'vox/{k}.words.json','w'),ensure_ascii=False);print(k,len(w))
async def main():
    for k,t in T.items():await one(k,t)
