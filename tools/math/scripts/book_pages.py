def code(lesson,ch):
    s=str(lesson or '').translate(str.maketrans('0123456789',AR))
    m=re.search(r'([١-٦])\s*[‎‏\-‐‑–]\s*([١-٨])',s)
    if m and m.group(1)==a(ch):return m.group(1)+'-'+m.group(2)
    return None
def info(lesson,ch):
    c=code(lesson,ch)
    for k,t,s,e in LES.get(ch,[]):
        if k.replace('-','-')==c: return (k,t,s,e)
    return None
def label(lesson,ch):
    i=info(lesson,ch)
    if i:
        k,t,s,e=i;pg=f'ص{a(s)}' if s==e else f'ص{a(s)}–{a(e)}'
        return f'الفصل {a(ch)} · الدرس {k} {t} · {pg}'
    return f'الفصل {a(ch)} · مراجعة: {REVIEW[ch]}'
